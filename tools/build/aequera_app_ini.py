"""Write Aequera's application.ini from the build's own.

Gives the artifact build its own application identity so it runs beside a
normal Firefox without sharing anything (patches/build/branding/README.md,
"Profile separation"):

  Vendor/Name    -> Aequera (window class, registry, crash/app identity)
  RemotingName   -> aequera (single-instance channel: never hands off to or
                    from a running Firefox)
  Profile        -> Aequera (profile root %APPDATA%\\Aequera\\Profiles and
                    %LOCALAPPDATA%\\Aequera\\Profiles, its own profiles.ini)

Everything else (Version, BuildID, the Firefox application ID that keeps
WebExtension compatibility, the Gecko version range) is copied unchanged from
the build, so a rebuild can never drift out of sync.

The prebuilt firefox.exe of an artifact build only reads this file when
started with `-app <path>` (tools/build/aequera-run.sh does that). The exe's
own icon and file name stay Firefox's until a full branding build.

Usage: python aequera_app_ini.py <build application.ini> <output ini>
"""

import configparser
import sys

IDENTITY = {
    "Vendor": "Aequera",
    "Name": "Aequera",
    "RemotingName": "aequera",
    "Profile": "Aequera",
}


def main(source: str, target: str) -> int:
    ini = configparser.ConfigParser(interpolation=None)
    ini.optionxform = str  # keys are case-sensitive for XRE
    with open(source, encoding="utf-8") as handle:
        ini.read_file(handle)
    if not ini.has_section("App") or not ini.has_option("App", "ID"):
        print(f"{source}: no [App] ID; not a Firefox application.ini", file=sys.stderr)
        return 1
    for key, value in IDENTITY.items():
        ini.set("App", key, value)
    with open(target, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("; Generated by tools/build/aequera_app_ini.py - do not edit.\n")
        ini.write(handle, space_around_delimiters=False)
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
